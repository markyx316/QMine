#: 分诊优先级：命中这些的，覆盖其它命中（码本的规则，不是词表的偏好）
PRIORITY = ["EK", "FCK_CK"]


def compile_lex() -> dict[str, re.Pattern]:
    return {k: re.compile("|".join(re.escape(t) for t in v)) for k, v in LEX.items()}


def classify(q: str, pats: dict[str, re.Pattern]) -> tuple[str, int, str]:
    hits = {k: p.findall(q) for k, p in pats.items()}
    hits = {k: v for k, v in hits.items() if v}
    if not hits:
        return "ABSTAIN_NO_EVIDENCE", 0, ""
    terms = ";".join(sorted({t for v in hits.values() for t in v}))
    for pri in PRIORITY:
        if pri in hits:
            return pri, len(hits), terms
    if len(hits) > 1:
        return "ABSTAIN_AMBIGUOUS", len(hits), terms
    return next(iter(hits)), 1, terms


def main() -> int:
    pats = compile_lex()
    dupes = {}
    for a in LEX:
        for b in LEX:
            if a < b:
                both = set(LEX[a]) & set(LEX[b])
                if both:
                    dupes[(a, b)] = sorted(both)
    assert not dupes, f"a term claimed by two departments: {dupes}"
    g = pd.read_csv(BASE / "inputs.csv", encoding="utf-8-sig", keep_default_na=False)
    res = [classify(q, pats) for q in g["query"].astype(str)]
    g["rule_code"] = [r[0] for r in res]
    g["n_dept_hit"] = [r[1] for r in res]
    g["hit_terms"] = [r[2] for r in res]
    g.to_csv(BASE / "rule_labels.csv", index=False, encoding="utf-8-sig")
    spoke = ~g["rule_code"].str.startswith("ABSTAIN")
    print(f"{len(g):,} strings | rule spoke on {int(spoke.sum()):,} ({100*spoke.mean():.1f}%) | "
          f"abstained no-evidence {int((g.rule_code=='ABSTAIN_NO_EVIDENCE').sum()):,} | "
          f"ambiguous {int((g.rule_code=='ABSTAIN_AMBIGUOUS').sum()):,}")
    print(g.loc[spoke, "rule_code"].value_counts().head(15).to_string())
    print(f"→ {BASE / 'rule_labels.csv'}")
    return 0


